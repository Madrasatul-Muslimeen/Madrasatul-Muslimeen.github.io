// English and Bangla translations of the eight books the library numbers (the Owner, 8 Oct 2026: "include the Hadith
// Eng n Bangla languages from the sources you have identified (permissions will not be a problem, it will be okay,
// En Shaa Allah)"; decision 89).
//
// SOURCE. fawazahmed0/hadith-api@1, editions eng-<book> and ben-<book> (the research report
// docs/reports/2026-10-07-hadith-dua-sources-research.md names it). Each hadith there carries `hadithnumber`, the same
// standard (sunnah.com) number the concordance stores as `standardNumber` for every OpenITI passage it matched, so a
// passage in the library finds its translation by that number. The repository is published under the Unlicense; the
// translations inside it belong to their translators and publishers, which is what the Owner's statement on
// permission covers, and every file and every card names the source.
//
// WHAT IT WRITES. tools/hadith-data-pull/output/translations/<edition>/<lang>/<k>.json, each holding the standard
// numbers k*500 .. k*500+499 as { "<number>": "<text>" } (empty texts dropped), and translations/summary.json with the
// counts and credits. The app reads one chunk when a reader opens a translation (I9: nothing at startup).
//
// Usage (repository root):  NODE_USE_ENV_PROXY=1 node tools/hadith-data-pull/hadith-translations-pull.mjs
// tools/i18n-verify/hadith-translations.mjs checks the output.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "output", "translations");
const API = "https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1";
export const CHUNK = 500;
export const BOOKS = [
  { versionUri: "0256Bukhari.Sahih.JK000110-ara1", edition: "bukhari" },
  { versionUri: "0261Muslim.Sahih.Shamela0001727-ara1", edition: "muslim" },
  { versionUri: "0275AbuDawudSijistani.Sunan.JK000142-ara1", edition: "abudawud" },
  { versionUri: "0279Tirmidhi.Sunan.JK000140-ara1", edition: "tirmidhi" },
  { versionUri: "0303Nasai.SunanSughra.JK000130-ara1", edition: "nasai" },
  { versionUri: "0273IbnMaja.Sunan.JK000141-ara1", edition: "ibnmajah" },
  { versionUri: "0179MalikIbnAnas.Muwatta.Shamela0028107-ara1", edition: "malik" },
  { versionUri: "0676Nawawi.ArbacunaNawawiyya.Shamela0012836-ara1", edition: "nawawi" },
];
const LANGS = [["en", "eng"], ["bn", "ben"]];

/** hadith-api's `author`: a translator's name, or "Unknown", or (for an-Nawawi's Forty) the book's own author. */
export function translatorOf(author) {
  const a = String(author ?? "").trim();
  return a && a !== "Unknown" && !/nawawi/i.test(a) ? a : null;
}

/** Pure: one edition's hadiths -> { chunks: Map<k, {number: text}>, count }. Text trimmed, empty dropped. */
export function chunkEdition(hadiths) {
  const chunks = new Map();
  let count = 0;
  for (const h of hadiths) {
    const n = Math.trunc(Number(h.hadithnumber));
    const text = String(h.text ?? "").replace(/\s+/g, " ").trim();
    if (!(n > 0) || !text) continue;
    const k = Math.floor(n / CHUNK);
    if (!chunks.has(k)) chunks.set(k, {});
    const c = chunks.get(k);
    c[n] = c[n] ? `${c[n]} ${text}` : text;
    count++;
  }
  return { chunks, count };
}

async function main() {
  const editions = await (await fetch(`${API}/editions.json`)).json();
  const summary = { schemaVersion: 1, note: "Generated by tools/hadith-data-pull/hadith-translations-pull.mjs. Do not edit by hand.",
    source: "fawazahmed0/hadith-api@1", sourceUrl: "https://github.com/fawazahmed0/hadith-api", chunk: CHUNK,
    permission: "The Owner, 8 Oct 2026 (decision 89): \"permissions will not be a problem, it will be okay, En Shaa Allah\".", books: [] };
  for (const b of BOOKS) {
    const row = { versionUri: b.versionUri, edition: b.edition, langs: {} };
    for (const [lang, code] of LANGS) {
      const name = `${code}-${b.edition}`;
      const meta = editions[b.edition]?.collection?.find((c) => c.name === name);
      if (!meta) { console.log(`  ${name}: not published`); continue; }
      const res = await fetch(`${API}/editions/${name}.min.json`);
      if (!res.ok) throw new Error(`${name}: ${res.status}`);
      const { chunks, count } = chunkEdition((await res.json()).hadiths ?? []);
      const dir = path.join(OUT, b.edition, lang);
      fs.rmSync(dir, { recursive: true, force: true });
      fs.mkdirSync(dir, { recursive: true });
      for (const [k, c] of [...chunks].sort((x, y) => x[0] - y[0])) fs.writeFileSync(path.join(dir, `${k}.json`), JSON.stringify(c));
      row.langs[lang] = { edition: name, translator: translatorOf(meta.author), count, chunks: [...chunks.keys()].sort((x, y) => x - y) };
      console.log(`  ${name}: ${count} hadith in ${chunks.size} files`);
    }
    summary.books.push(row);
  }
  fs.writeFileSync(path.join(OUT, "summary.json"), JSON.stringify(summary, null, 1));
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) await main();
