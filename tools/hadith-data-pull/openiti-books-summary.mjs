// The OpenITI book list's own summary (the Owner, 6 Oct 2026: "opening of all files, modules takes ages").
// The Hadith page's OpenITI book list needs each book's title and count, and until now got them by loading
// EVERY book's whole index.json (1.8 MB for 11 books) before it could draw a single row. This writes the
// eleven rows -- nothing else -- to split/books-summary.json, in the manifest's own order, so the list costs
// one small file and a book's index loads only when that book is opened.
// Run from the repository root after openiti-split.mjs:  node tools/hadith-data-pull/openiti-books-summary.mjs
// tools/i18n-verify/openiti-books-summary.mjs fails if this file drifts from the indexes it summarises.
import fs from "node:fs";
const BASE = "tools/hadith-data-pull/output/openiti-release/";
const FIELDS = ["versionUri", "titleAr", "titleEn", "numbering", "passageCount", "hadithCount"];
export function buildBooksSummary(manifest, readIndex) {
  return {
    schemaVersion: 1,
    sourceId: "openiti-release",
    note: "Generated by tools/hadith-data-pull/openiti-books-summary.mjs from each book's index.json. Do not edit by hand.",
    books: manifest.files.map((f) => {
      const index = readIndex(f.version_uri);
      return Object.fromEntries(FIELDS.map((k) => [k, index[k] ?? null]));
    }),
  };
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const manifest = JSON.parse(fs.readFileSync(`${BASE}manifest.json`, "utf8"));
  const summary = buildBooksSummary(manifest, (uri) => JSON.parse(fs.readFileSync(`${BASE}split/${uri}/index.json`, "utf8")));
  fs.writeFileSync(`${BASE}split/books-summary.json`, JSON.stringify(summary, null, 1) + "\n");
  console.log(`wrote ${summary.books.length} books, ${fs.statSync(`${BASE}split/books-summary.json`).size} bytes`);
}
