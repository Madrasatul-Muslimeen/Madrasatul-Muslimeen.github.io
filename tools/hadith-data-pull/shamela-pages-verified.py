#!/usr/bin/env python3
"""Build a Shamela page map for a book whose hadith numbers are the edition's own (Musnad Ahmad), and keep a page ONLY when our text agrees.

shamela-pages-build.py trusts the number printed at the head of a Shamela paragraph. For Musnad Ahmad that was not enough: a paragraph
number can be a list item in the editor's introduction ("2 - ..."), and a few numbers differ between our OpenITI text and the printed
edition. So for every hadith number n this tool collects EVERY paragraph that starts with n, in the cached pages, compares the opening
words of each with our record's (difflib ratio over the first 20 words, after folding the usual isnad variants), and keeps the best one if
it scores at least --min (default 0.6). Anything else gets no page (0): no link rather than a guess.

    python3 -I tools/hadith-data-pull/shamela-pages-verified.py ahmad --cache /path/to/cache
Reads only the cache the crawler filled (shamela-pages-build.py); makes no request.
"""
import argparse, difflib, glob, importlib.util, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
def load(name):
    spec = importlib.util.spec_from_file_location(name.replace("-", "_"), os.path.join(HERE, name + ".py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
rz, build = load("shamela-pages-riyad"), load("shamela-pages-build")
DIG = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")
PARA = re.compile(r'<p>\s*(?:<span\b[^>]*\bclass="anchor"[^>]*></span>\s*)?([٠-٩0-9]+)\s*[-–](?=[\s<])\s*(.*?)</p>', re.S)
FOLD = {"ثنا": "حدثنا", "نا": "حدثنا", "اخبرنا": "حدثنا", "بن": "ابن"}
DROP = {"رضي", "الله", "عنه", "عنها", "عنهما", "صلي", "عليه", "وسلم"}
fold = lambda ws: [FOLD.get(w, w) for w in ws if w not in DROP]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("key"); ap.add_argument("--cache", required=True); ap.add_argument("--min", type=float, default=0.6)
    a = ap.parse_args()
    row = next(b for b in json.load(open(build.REGISTRY, encoding="utf-8"))["books"] if b["key"] == a.key)
    sh, top = row["shamela"], row["lastNumber"]
    ours = {}
    for f in glob.glob(os.path.join(HERE, "output", "openiti-release", "split", row["versionUri"], "ch-*.json")):
        for r in json.load(open(f, encoding="utf-8"))["hadiths"]:
            if r["kind"] == "hadith" and r.get("number"):
                ours.setdefault(int(r["number"]), fold(rz.norm(r["text"]))[:20])
    occ = {}  # number -> [(index, vol, page, words)]
    pages = 0
    for i in range(1, sh["lastIndex"] + 1):
        p = os.path.join(a.cache, f"{sh['id']}-{i}.html")
        if not os.path.exists(p): continue
        body = open(p, encoding="utf-8").read()
        m = build.TITLE.search(body)
        if not m: continue
        pages += 1
        vol, pg = int(m.group(1) or 0), int(m.group(2))
        st = body.find('<div class="nass'); en = body.find('<div class="text-center margin-top-20', st)
        seg = body[st:en] if st >= 0 and en > st else body
        for num, rest in PARA.findall(seg):
            n = int(num.translate(DIG))
            if n in ours: occ.setdefault(n, []).append((i, vol, pg, fold(rz.norm(rz.TAGS.sub(" ", rest)))[:20]))
    arr = {"i": [0] * top, "v": [0] * top, "g": [0] * top}
    kept = dropped = nonum = changed = 0
    for n in range(1, top + 1):
        if n not in ours:
            nonum += 1; continue
        best = max(((difflib.SequenceMatcher(None, ours[n], w, autojunk=False).ratio(), -i, i, v, g) for i, v, g, w in occ.get(n, [])), default=None)
        if best and best[0] >= a.min:
            arr["i"][n - 1], arr["v"][n - 1], arr["g"][n - 1] = best[2], best[3], best[4]; kept += 1
            if occ[n][0][0] != best[2]: changed += 1
        else:
            dropped += 1
    back, prev = 0, 0
    for x in arr["i"]:
        if x:
            if x < prev: back += 1
            prev = x
    out = {"schemaVersion": 1, "kind": "shamela",
           "note": "Generated by tools/hadith-data-pull/shamela-pages-verified.py from pages read by shamela-pages-build.py. A page is kept only when our text's opening words agree with the paragraph carrying that number (difflib >= %.2f); otherwise 0. Do not edit by hand." % a.min,
           "book": a.key, "shamelaId": sh["id"], "edition": sh["edition"], "numbers": top, **arr}
    os.makedirs(build.OUT_DIR, exist_ok=True)
    with open(os.path.join(build.OUT_DIR, f"{a.key}.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    print(f"pages read {pages}; numbers with a record {len(ours)}; kept {kept} (of which {changed} chose a later occurrence than the first); dropped for disagreeing text or no paragraph {dropped}; numbers our text lacks {nonum}; pages going backwards {back}")


if __name__ == "__main__":
    main()
