#!/usr/bin/env python3
"""Printed-page map for a Shamela book whose printed edition NUMBERS ITS HADITH DIFFERENTLY from our copy (the Owner ticked hd1111n E, 11 Nov 2026:
Sunan al-Darimi). Keyed by OUR record order `n`, like shamela-pages-riyad.py, whose matching it reuses:

  1. read every page of the Shamela book (cached OUTSIDE the repo): each hadith paragraph starts "N - text" in Arabic-Indic digits;
  2. take our hadith records in order of `n`;
  3. match the two lists by the OPENING WORDS (first 30 words, sequence similarity >= 0.8: a banded longest-common-subsequence), then a
     second pass for blocks the two texts order differently (20, then 12 opening words, unique on both sides);
  4. a record not matched stays 0 (no link, never a guess).

Writes output/book-pages/<key>.json = { i, v, g } and prints a report.

    python3 -I tools/hadith-data-pull/shamela-pages-align.py darimi --cache /path/outside/the/repo
"""
import argparse, glob, importlib.util, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REGISTRY = os.path.join(HERE, "sources", "book-pages.json")
OUT_DIR = os.path.join(HERE, "output", "book-pages")
SPLIT_ROOT = os.path.join(HERE, "output", "openiti-release", "split")
ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")
TITLE = re.compile(r"<title>\s*(?:ج(\d+)\s*-\s*)?ص(\d+)\s*-")
# a hadith paragraph: <p> [anchor] ١٦٣٤ - text </p>
PARA = re.compile(r'<p>\s*(?:<span\b[^>]*\bclass="anchor"[^>]*></span>\s*)?([٠-٩0-9]+)\s*[-–]\s*(.*?)</p>', re.S)


def load_riyad_module():
    spec = importlib.util.spec_from_file_location("rz", os.path.join(HERE, "shamela-pages-riyad.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("key")
    ap.add_argument("--cache", required=True)
    a = ap.parse_args()
    rz = load_riyad_module()
    reg = json.load(open(REGISTRY, encoding="utf-8"))
    row = next(b for b in reg["books"] if b["key"] == a.key)
    sh_cfg = row["shamela"]
    sh = []
    for i in range(1, sh_cfg["lastIndex"] + 1):
        body = open(os.path.join(a.cache, f"{sh_cfg['id']}-{i}.html"), encoding="utf-8").read()
        m = TITLE.search(body)
        if not m:
            continue
        vol, page = int(m.group(1) or 0), int(m.group(2))
        start = body.find('<div class="nass')
        end = body.find('<div class="text-center margin-top-20', start) if start >= 0 else -1
        seg = body[start:end] if start >= 0 and end > start else body
        for num, rest in PARA.findall(seg):
            sh.append({"i": i, "v": vol, "g": page, "in": int(num.translate(ARABIC_DIGITS)), "gl": int(num.translate(ARABIC_DIGITS)),
                       "w": rz.head(rz.norm(rz.TAGS.sub(" ", rest)))})
    kinds = row.get("alignKinds", ["hadith"])
    recs = []
    for f in glob.glob(os.path.join(SPLIT_ROOT, row["versionUri"], "ch-*.json")):
        recs += json.load(open(f, encoding="utf-8"))["hadiths"]
    recs.sort(key=lambda r: r["n"])
    ours = [r for r in recs if r["kind"] in kinds]
    res, notes = rz.align(ours, sh)
    top = row["lastNumber"]
    arrs = {"i": [0] * top, "v": [0] * top, "g": [0] * top}
    for n, e in res.items():
        arrs["i"][n - 1], arrs["v"][n - 1], arrs["g"][n - 1] = e["i"], e["v"], e["g"]
    out = {"schemaVersion": 1, "kind": "shamela", "keyBy": "n",
           "note": f"Generated by tools/hadith-data-pull/shamela-pages-align.py. Do not edit by hand. Keyed by OUR record order n. i/v/g[n-1] = Shamela page index, volume, printed page of record n (0 = none).",
           "book": a.key, "shamelaId": sh_cfg["id"], "edition": sh_cfg["edition"], "numbers": top, **arrs}
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, f"{a.key}.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    print(f"Shamela paragraphs: {len(sh)}; our records of kind {kinds}: {len(ours)}; mapped: {len(res)} ({100*len(res)/max(1,len(ours)):.1f}%)")
    print(f"{len(notes)} walk notes (first 12):")
    for n in notes[:12]:
        print(" ", n)
    prev, back = 0, 0
    for n in sorted(res):
        back += res[n]["i"] < prev
        prev = res[n]["i"]
    print(f"records whose page is earlier than the previous record's: {back}")


if __name__ == "__main__":
    main()
